def _fig_inscribed_proof() -> str:
    O, r = P(230, 165), 112
    aA, aB, aP = 200.0, 340.0, 85.0
    A, B, Pp = polar(O, r, aA), polar(O, r, aB), polar(O, r, aP)
    Q = polar(O, r, (aP + 180) % 360)   # diametrically opposite P
    b = [arrowdefs()]
    b.append(txt(P(30, 30), "พิสูจน์: มุมที่จุดศูนย์กลาง = 2 × มุมในส่วนโค้ง",
                 "t-tag", "start"))
    b.append(circ(O, r, "s-ink"))
    b.append(f'<g data-step="1">{line(Pp, A, "s-teal")}{line(Pp, B, "s-teal")}'
             f'{angle_mark(Pp, A, B, 28, "s-teal")}</g>')
    b.append(f'<g data-step="2">{line(O, A, "s-link")}{line(O, B, "s-link")}'
             f'{angle_mark(O, A, B, 32, "s-link")}</g>')
    b.append(f'<g data-step="3">{line(Pp, Q, "s-accent dash")}'
             f'{dot(Q, 4, "f-accent")}'
             f'{txt(P(Q.x, Q.y + 20), "Q", "t-name t-accent")}</g>')
    b.append(f'<g data-step="4">{ticks(O, A, 1, 6, "s-violet")}'
             f'{ticks(O, Pp, 1, 6, "s-violet")}'
             f'{ticks(O, B, 2, 5, "s-violet", 4)}</g>')
    for nm, p, dx, dy in (("A", A, -14, 4), ("B", B, 14, 4), ("P", Pp, 0, -14),
                          ("O", O, -14, 6)):
        b.append(dot(p, 4.2, "f-ink"))
        b.append(txt(P(p.x + dx, p.y + dy), nm, "t-name"))
    rows = [
        (r"\(\angle APB\) เป็นมุมในส่วนโค้งที่รองรับคอร์ด \(AB\)", "นิยาม"),
        (r"\(\angle AOB\) เป็นมุมที่จุดศูนย์กลางที่รองรับคอร์ดเดียวกัน", "นิยาม"),
        (r"ลาก \(PO\) ต่อออกไปพบวงกลมที่ \(Q\)", "สร้างเส้นช่วย — เส้นผ่านศูนย์กลาง"),
        (r"\(OA=OP=OB=r\)", "รัศมีของวงกลมเดียวกันยาวเท่ากัน"),
        (r"\(\triangle OAP\) และ \(\triangle OBP\) เป็นสามเหลี่ยมหน้าจั่ว",
         "มีด้านประกอบมุมยอดยาวเท่ากัน (ข้อ 4)"),
        (r"\(\angle AOQ=2\angle APO\) และ \(\angle BOQ=2\angle BPO\)",
         "ทฤษฎีบทมุมภายนอกของสามเหลี่ยมหน้าจั่ว"),
        (r"\(\angle AOB=\angle AOQ+\angle BOQ=2(\angle APO+\angle BPO)=2\angle APB\)",
         "บวกกัน และ \\(Q\\) อยู่ภายในมุม \\(\\angle AOB\\)"),
    ]
    return fig_proof(
        "proof-inscribed", "การพิสูจน์ทฤษฎีบทมุมในส่วนโค้ง",
        "วงกลมจุดศูนย์กลาง O มีคอร์ด AB จุด P บนส่วนโค้งใหญ่ "
        "ลากเส้นผ่านศูนย์กลางจาก P ผ่าน O ไปพบวงกลมที่ Q "
        "ทำให้เกิดสามเหลี่ยมหน้าจั่วสองรูปที่ให้ข้อสรุปว่ามุม AOB เป็นสองเท่าของมุม APB",
        480, 340, "".join(b), rows,
        "เส้นช่วยสำคัญคือ <b>เส้นผ่านศูนย์กลาง \\(PQ\\)</b> ซึ่งแยกมุมออกเป็นสองส่วน "
        "ที่จัดการได้ด้วยสามเหลี่ยมหน้าจั่ว — กดไล่ขั้นเพื่อดูว่าแต่ละขั้นเพิ่มอะไรเข้ามา",
    )


