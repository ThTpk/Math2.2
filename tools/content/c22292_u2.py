# --- รูปประกอบ: ส่วนประกอบของวงกลม ------------------------------------------
def _fig_parts() -> str:
    from svgkit import svg
    from layout import figure
    O, r = P(230, 160), 110
    A, B = polar(O, r, 205), polar(O, r, 335)
    C, D = polar(O, r, 118), polar(O, r, 42)
    T = polar(O, r, 270)
    tdir = (T - O).n.perp
    b = [arrowdefs()]
    b.append(txt(P(30, 30), "ส่วนประกอบของวงกลม", "t-tag", "start"))
    b.append(circ(O, r, "s-ink"))
    # diameter through O
    b.append(line(polar(O, r, 0), polar(O, r, 180), "s-link"))
    b.append(txt(P(O.x + 46, O.y - 8), "เส้นผ่านศูนย์กลาง", "t-mono t-link"))
    # radius
    b.append(line(O, C, "s-teal"))
    b.append(txt(mid(O, C) + P(-18, -4), "รัศมี r", "t-mono t-teal", "end"))
    # chord
    b.append(line(A, B, "s-accent thick"))
    b.append(txt(mid(A, B) + P(0, 20), "คอร์ด AB", "t-mono t-accent"))
    # arc
    b.append(path(arc_d(O, r + 9, 42, 118), "s-violet thick"))
    b.append(txt(polar(O, r + 26, 80), "ส่วนโค้ง CD", "t-mono t-violet"))
    # tangent
    b.append(line(T - tdir * 95, T + tdir * 95, "s-accent dash"))
    b.append(txt(P(T.x + 70, T.y + 18), "เส้นสัมผัส", "t-mono t-accent"))
    b.append(right_mark(T, O, T + tdir * 20, 11, "s-muted"))
    # secant
    S0 = polar(O, r, 150)
    S1 = polar(O, r, 20)
    b.append(line(lerp(S0, S1, -0.3), lerp(S0, S1, 1.3), "s-muted dash-fine"))
    b.append(txt(lerp(S0, S1, 1.3) + P(10, -6), "เส้นตัด", "t-mono", "start"))
    for nm, p, dx, dy in (("A", A, -14, 4), ("B", B, 14, 4), ("C", C, -6, -12),
                          ("D", D, 10, -8), ("O", O, -4, 18), ("T", T, 0, 22)):
        b.append(dot(p, 4, "f-ink"))
        b.append(txt(P(p.x + dx, p.y + dy), nm, "t-name"))
    b.append(legend(316, 480, [("s-teal", "รัศมี"), ("s-link", "เส้นผ่านศูนย์กลาง"),
                               ("s-accent thick", "คอร์ด"), ("s-violet thick", "ส่วนโค้ง")]))
    sv = svg(480, 350, "".join(b), "fig-circle-parts", "ส่วนประกอบของวงกลม",
             "วงกลมจุดศูนย์กลาง O แสดงรัศมี เส้นผ่านศูนย์กลาง คอร์ด ส่วนโค้ง "
             "เส้นสัมผัสที่ตั้งฉากกับรัศมีที่จุดสัมผัส และเส้นตัดที่ผ่านวงกลมสองจุด")
    return figure(sv, "<b>เส้นสัมผัส</b> แตะวงกลมที่จุดเดียวและตั้งฉากกับรัศมี "
                      "ณ จุดสัมผัสเสมอ ขณะที่ <b>เส้นตัด</b> ผ่านวงกลมสองจุด "
                      "ข้อเท็จจริงเรื่องเส้นสัมผัสตั้งฉากกับรัศมีเป็นจุดเริ่มต้นของ "
                      "ทฤษฎีบทเส้นสัมผัสทุกข้อ")


