# --- รูปประกอบ: การพิสูจน์แบบทีละขั้น (สี่เหลี่ยมด้านขนาน) -------------------
def _fig_parallelogram_proof() -> str:
    A, B = P(90, 210), P(300, 210)
    C, D = P(380, 90), P(170, 90)
    O = P((A.x + C.x) / 2, (A.y + C.y) / 2)
    b = [arrowdefs()]
    b.append(txt(P(30, 32), "สี่เหลี่ยมด้านขนาน: เส้นทแยงมุมแบ่งครึ่งกัน", "t-tag", "start"))
    b.append(poly(A, B, C, D, cls="f-it"))
    b.append(poly(A, B, C, D, cls="s-ink"))
    # step 1 — diagonals
    b.append(f'<g data-step="1">{line(A, C, "s-accent")}{line(B, D, "s-link")}'
             f'{dot(O, 4.5, "f-accent")}'
             f'{txt(P(O.x + 12, O.y + 14), "O", "t-name t-accent")}</g>')
    # step 2 — alternate angles at A and C
    b.append(f'<g data-step="2">{angle_mark(A, B, C, 26, "s-accent")}'
             f'{angle_mark(C, D, A, 26, "s-accent")}</g>')
    # step 3 — alternate angles at B and D
    b.append(f'<g data-step="3">{angle_mark(B, A, D, 22, "s-link")}'
             f'{angle_mark(D, C, B, 22, "s-link")}</g>')
    # step 4 — equal opposite sides
    b.append(f'<g data-step="4">{ticks(A, B, 1, 7, "s-teal")}'
             f'{ticks(C, D, 1, 7, "s-teal")}</g>')
    # step 5 — the halves
    b.append(f'<g data-step="5">{ticks(A, O, 2, 6, "s-accent", 4)}'
             f'{ticks(O, C, 2, 6, "s-accent", 4)}'
             f'{ticks(B, O, 3, 6, "s-link", 4)}'
             f'{ticks(O, D, 3, 6, "s-link", 4)}</g>')
    for nm, p, dx, dy in (("A", A, -16, 8), ("B", B, 8, 20), ("C", C, 16, 2), ("D", D, -8, -12)):
        b.append(dot(p, 4.2))
        b.append(txt(P(p.x + dx, p.y + dy), nm, "t-name"))
    b.append(legend(272, 460, [("s-accent", "คู่ที่ 1"), ("s-link", "คู่ที่ 2"),
                               ("s-teal", "ด้านตรงข้าม")]))
    rows = [
        (r"ลาก \(AC\) และ \(BD\) ตัดกันที่ \(O\)", "สร้างเส้นช่วย"),
        (r"\(\angle OAB=\angle OCD\)", r"มุมแย้งของ \(AB\parallel DC\) ที่มี \(AC\) เป็นเส้นตัด"),
        (r"\(\angle OBA=\angle ODC\)", r"มุมแย้งของ \(AB\parallel DC\) ที่มี \(BD\) เป็นเส้นตัด"),
        (r"\(AB=CD\)", "ด้านตรงข้ามของสี่เหลี่ยมด้านขนานยาวเท่ากัน"),
        (r"\(\triangle OAB\equiv\triangle OCD\)", "ม.ด.ม. จากข้อ 2, 4, 3"),
        (r"\(OA=OC\) และ \(OB=OD\)", "ส่วนสมนัยของรูปที่เท่ากันทุกประการย่อมเท่ากัน"),
    ]
    body = "".join(b)
    return fig_proof(
        "proof-parallelogram",
        "การพิสูจน์ว่าเส้นทแยงมุมของสี่เหลี่ยมด้านขนานแบ่งครึ่งกัน",
        "รูปสี่เหลี่ยมด้านขนาน ABCD มีเส้นทแยงมุม AC และ BD ตัดกันที่จุด O "
        "มีการกำกับมุมแย้งสองคู่และด้านตรงข้ามที่เท่ากัน "
        "นำไปสู่ข้อสรุปว่า OA เท่ากับ OC และ OB เท่ากับ OD",
        460, 300, body,
        rows,
        "กดปุ่ม <b>ขั้นต่อไป</b> เพื่อไล่ดูการพิสูจน์ทีละขั้น "
        "รูปและตารางเหตุผลจะเปิดเผยพร้อมกัน ทำให้เห็นว่าแต่ละข้อความ "
        "อ้างอิงอะไรในรูป",
    )


# --- รูปประกอบ: เส้นกึ่งกลาง (midsegment) -----------------------------------
def _fig_midsegment() -> str:
    A, B, C = P(230, 62), P(80, 222), P(380, 222)
    M, N = mid(A, B), mid(A, C)
    b = [arrowdefs()]
    b.append(txt(P(30, 32), "เส้นกึ่งกลางของรูปสามเหลี่ยม", "t-tag", "start"))
    b.append(poly(A, B, C, cls="f-it"))
    b.append(poly(A, B, C, cls="s-ink"))
    b.append(f'<g data-step="1">{dot(M, 4.5, "f-accent")}{dot(N, 4.5, "f-accent")}'
             f'{ticks(A, M, 1, 7, "s-accent")}{ticks(M, B, 1, 7, "s-accent")}'
             f'{ticks(A, N, 2, 6, "s-accent", 4)}{ticks(N, C, 2, 6, "s-accent", 4)}'
             f'{txt(P(M.x - 16, M.y), "M", "t-name t-accent")}'
             f'{txt(P(N.x + 16, N.y), "N", "t-name t-accent")}</g>')
    b.append(f'<g data-step="2">{line(M, N, "s-accent thick")}</g>')
    b.append(f'<g data-step="3">{angle_mark(M, N, B, 0.1, "s-rule")}'
             f'{angle_mark(B, M, C, 24, "s-link")}'
             f'{angle_mark(M, A, N, 20, "s-link")}</g>')
    b.append(f'<g data-step="4">'
             f'{txt(P(mid(M, N).x, mid(M, N).y - 10), "MN", "t-mono t-accent")}'
             f'{txt(P(mid(B, C).x, mid(B, C).y + 20), "BC = 2·MN", "t-mono t-accent")}</g>')
    for nm, p, dx, dy in (("A", A, 0, -12), ("B", B, -16, 16), ("C", C, 16, 16)):
        b.append(dot(p, 4.2))
        b.append(txt(P(p.x + dx, p.y + dy), nm, "t-name"))
    rows = [
        (r"\(M,N\) เป็นจุดกึ่งกลางของ \(AB,AC\)", "กำหนดให้"),
        (r"ลาก \(MN\)", "สร้างเส้นช่วย"),
        (r"\(\angle AMN=\angle ABC\)", r"จาก \(\triangle AMN\sim\triangle ABC\) (อัตราส่วน \(1:2\) และมุม \(A\) ร่วม)"),
        (r"\(MN\parallel BC\) และ \(MN=\tfrac12 BC\)", "มุมแย้งเท่ากัน → ขนาน; อัตราส่วนความคล้าย → ครึ่งหนึ่ง"),
    ]
    return fig_proof(
        "proof-midsegment", "เส้นกึ่งกลางของรูปสามเหลี่ยม",
        "รูปสามเหลี่ยม ABC มีจุด M และ N เป็นจุดกึ่งกลางของด้าน AB และ AC "
        "ส่วนของเส้นตรง MN ขนานกับด้าน BC และยาวครึ่งหนึ่งของ BC",
        460, 280, "".join(b), rows,
        "<b>ทฤษฎีบทเส้นกึ่งกลาง</b> — ส่วนของเส้นตรงที่เชื่อมจุดกึ่งกลางของด้านสองด้าน "
        "ย่อมขนานกับด้านที่สามและยาวเป็นครึ่งหนึ่งของด้านนั้น "
        "ทฤษฎีบทนี้ใช้แก้โจทย์รูปสี่เหลี่ยมได้บ่อยมาก",
    )


