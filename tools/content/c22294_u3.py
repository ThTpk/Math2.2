        "ซึ่งห่างจากจุดยอดทั้งสามเท่ากัน จึงเป็นจุดศูนย์กลางของวงกลมที่ผ่านจุดยอดทั้งสาม",
        480, 400, "".join(b), rows,
        "สังเกตว่าต้องสร้างเส้นแบ่งครึ่งตั้งฉากเพียง <b>สองเส้น</b> ก็พอ "
