    b.append(f'<g data-step="1">{circ(A, r, "s-link dash-fine")}</g>')
    b.append(f'<g data-step="2">{circ(B, r, "s-teal dash-fine")}</g>')
    b.append(f'<g data-step="3">{dot(Cu, 4.5, "f-accent")}{dot(Cd, 4.5, "f-accent")}'
             f'{txt(P(Cu.x + 14, Cu.y), "C", "t-name t-accent", "start")}'
             f'{txt(P(Cd.x + 14, Cd.y), "D", "t-name t-accent", "start")}</g>')
    b.append(f'<g data-step="4">{line(P(Cu.x, Cu.y - 26), P(Cd.x, Cd.y + 26), "s-accent thick")}'
             f'{dot(M, 4.5, "f-accent")}'
             f'{txt(P(M.x + 14, M.y - 10), "M", "t-name t-accent", "start")}'
             f'{right_mark(M, B, Cu, 12, "s-accent")}</g>')
    b.append(f'<g data-step="5">{ticks(A, Cu, 1, 7, "s-link")}{ticks(B, Cu, 1, 7, "s-teal")}'
             f'{ticks(A, Cd, 2, 6, "s-link", 4)}{ticks(B, Cd, 2, 6, "s-teal", 4)}</g>')
    for nm, p, dx, dy in (("A", A, -14, 6), ("B", B, 14, 6)):
        b.append(dot(p, 4.2))
