# --- รูปประกอบ: การสร้างเส้นแบ่งครึ่งมุม ------------------------------------
def _fig_angle_bisector() -> str:
    O = P(110, 230)
    a1, a2 = 72.0, 12.0
    L1, L2 = polar(O, 290, a1), polar(O, 300, a2)
    r1 = 110.0
    Pp, Q = polar(O, r1, a1), polar(O, r1, a2)
    r2 = 95.0
    # intersection of circles centred at Pp and Q with radius r2
    d = dist(Pp, Q)
    mm = mid(Pp, Q)
    hh = math.sqrt(max(0.0, r2 * r2 - (d / 2) ** 2))
    u = (Q - Pp).n.perp
    R = mm + u * hh
    if dist(O, R) < dist(O, mm):
        R = mm - u * hh
    b = [arrowdefs()]
    b.append(txt(P(30, 30), "สร้างเส้นแบ่งครึ่งมุม", "t-tag", "start"))
    b.append(line(O, L1, "s-ink"))
    b.append(line(O, L2, "s-ink"))
    b.append(f'<g data-step="1">{path(arc_d(O, r1, a2 - 6, a1 + 6), "s-link dash-fine")}'
             f'{dot(Pp, 4.5, "f-link")}{dot(Q, 4.5, "f-link")}'
             f'{txt(P(Pp.x - 8, Pp.y - 12), "P", "t-name t-link")}'
             f'{txt(P(Q.x - 4, Q.y + 20), "Q", "t-name t-link")}</g>')
    b.append(f'<g data-step="2">{circ(Pp, r2, "s-teal dash-fine")}'
             f'{circ(Q, r2, "s-teal dash-fine")}</g>')
    b.append(f'<g data-step="3">{dot(R, 5, "f-accent")}'
             f'{txt(P(R.x + 6, R.y - 14), "R", "t-name t-accent", "start")}'
             f'{line(O, O + (R - O).n * 300, "s-accent thick")}</g>')
    b.append(f'<g data-step="4">{angle_mark(O, L1, R, 46, "s-accent")}'
             f'{angle_mark(O, R, L2, 56, "s-accent")}</g>')
    b.append(dot(O, 4.5))
    b.append(txt(P(O.x - 16, O.y + 6), "O", "t-name"))
    rows = [
        (r"เขียนส่วนโค้งจุดศูนย์กลาง \(O\) ตัดแขนทั้งสองที่ \(P\) และ \(Q\)",
         r"ได้ \(OP=OQ\) เพราะเป็นรัศมีเดียวกัน"),
        (r"เขียนวงกลมรัศมีเท่ากันที่ \(P\) และที่ \(Q\) ตัดกันที่ \(R\)",
         r"ได้ \(PR=QR\)"),
        (r"ลาก \(OR\) — ได้เส้นแบ่งครึ่งมุม \(\angle POQ\)", "สิ่งที่ต้องการสร้าง"),
        (r"\(\triangle OPR\equiv\triangle OQR\) (ด.ด.ด.) จึง \(\angle POR=\angle QOR\)",
         r"\(OP=OQ\), \(PR=QR\), \(OR\) เป็นด้านร่วม"),
    ]
    return fig_proof(
        "constr-angbis", "การสร้างเส้นแบ่งครึ่งมุมด้วยวงเวียนและสันตรง",
        "มุมที่มีจุดยอด O มีส่วนโค้งตัดแขนทั้งสองที่จุด P และ Q "
        "แล้วเขียนวงกลมรัศมีเท่ากันที่ P และ Q ให้ตัดกันที่ R "
        "เส้นตรง OR แบ่งมุมนั้นออกเป็นสองมุมที่เท่ากัน",
        460, 330, "".join(b), rows,
        "วิธีนี้ใช้ได้เพราะเราสร้างสามเหลี่ยมสองรูปที่เท่ากันทุกประการด้วย "
        "<b>ด.ด.ด.</b> — ลองลากจุด \\(O\\) หรือเปลี่ยนขนาดมุมใน GeoGebra "
        "แล้วสังเกตว่าเส้นแบ่งครึ่งยังถูกต้องเสมอ นี่คือข้อดีของ "
        "<i>เรขาคณิตพลวัต</i>: ถ้าสร้างถูกตามนิยาม รูปจะไม่พังเมื่อลาก",
    )


