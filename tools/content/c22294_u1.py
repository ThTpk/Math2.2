    r = 125.0
    M = mid(A, B)
    hh = math.sqrt(r * r - (dist(A, B) / 2) ** 2)
    Cu, Cd = P(M.x, M.y - hh), P(M.x, M.y + hh)
    b = [arrowdefs()]
    b.append(txt(P(30, 30), "สร้างเส้นแบ่งครึ่งตั้งฉากของ AB", "t-tag", "start"))
