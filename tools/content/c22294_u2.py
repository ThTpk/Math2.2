# --- รูปประกอบ: สี่เหลี่ยมด้านขนานกับการวัด ---------------------------------
def _fig_parallelogram_measure() -> str:
    A, B = P(90, 215), P(300, 215)
    v = P(80, -105)
    D, C = A + v, B + v
    Hh = P(A.x + v.x, 215)          # foot of the height from D
    b = [arrowdefs()]
    b.append(txt(P(30, 30), "สี่เหลี่ยมด้านขนาน: ด้าน มุม และพื้นที่", "t-tag", "start"))
    b.append(poly(A, B, C, D, cls="f-at"))
    b.append(poly(A, B, C, D, cls="s-ink"))
    b.append(ticks(A, B, 1, 7, "s-accent"))
    b.append(ticks(D, C, 1, 7, "s-accent"))
    b.append(ticks(A, D, 2, 6, "s-link", 4))
    b.append(ticks(B, C, 2, 6, "s-link", 4))
    b.append(angle_mark(A, B, D, 26, "s-teal"))
    b.append(angle_mark(C, D, B, 26, "s-teal"))
    b.append(angle_mark(B, C, A, 22, "s-violet"))
    b.append(angle_mark(D, A, C, 22, "s-violet"))
    b.append(line(D, Hh, "s-teal dash"))
    b.append(right_mark(Hh, A, D, 11, "s-teal"))
    b.append(txt(P(Hh.x - 12, (Hh.y + D.y) / 2), "h", "t-mono t-teal", "end"))
    b.append(txt(P(Hh.x, Hh.y + 20), "H", "t-name t-teal"))
    b.append(txt(mid(A, B) + P(0, 24), "ฐาน b", "t-mono t-accent"))
    for nm, p, dx, dy in (("A", A, -16, 8), ("B", B, 12, 20), ("C", C, 16, 2),
                          ("D", D, -8, -12)):
        b.append(dot(p, 4.2))
        b.append(txt(P(p.x + dx, p.y + dy), nm, "t-name"))
    b.append(txt(P(30, 272), "พื้นที่ = b × h   (ไม่ใช่ b × ด้านเอียง)",
                 "t-val t-accent", "start"))
    b.append(legend(316, 460, [("s-accent", "ด้านคู่ที่ 1"), ("s-link", "ด้านคู่ที่ 2"),
                               ("s-teal dash", "ความสูง")]))
    sv = svg(460, 350, "".join(b), "fig-pgram-measure",
             "สี่เหลี่ยมด้านขนานกับความสูงที่ใช้คำนวณพื้นที่",
             "สี่เหลี่ยมด้านขนาน ABCD มีขีดกำกับด้านตรงข้ามที่ยาวเท่ากันสองคู่ "
             "ส่วนโค้งกำกับมุมตรงข้ามที่เท่ากันสองคู่ และเส้นประแสดงความสูงจากจุด D "
             "ตั้งฉากลงมายังฐาน AB ที่จุด H")
    return figure(sv, "ข้อผิดพลาดที่พบบ่อยที่สุดคือใช้ <b>ด้านเอียง</b> "
                      "แทนความสูง พื้นที่ของสี่เหลี่ยมด้านขนานคือ "
                      "\\(b\\times h\\) โดย \\(h\\) ต้องเป็นระยะ "
                      "<b>ตั้งฉาก</b> ระหว่างด้านขนานคู่นั้น "
                      "ซึ่งน้อยกว่าด้านเอียงเสมอ (เว้นแต่เป็นสี่เหลี่ยมมุมฉาก)")


# --- รูปประกอบ: พื้นที่สี่เหลี่ยมด้านขนาน = สี่เหลี่ยมผืนผ้า ----------------
def _fig_shear_proof() -> str:
    y0, y1 = 220.0, 120.0
    A, B = P(100, y0), P(280, y0)
    sh = 95.0
    D, C = P(A.x + sh, y1), P(B.x + sh, y1)
    Hh = P(D.x, y0)
    b = [arrowdefs()]
    b.append(txt(P(30, 30), "เหตุใดพื้นที่ = ฐาน × สูง", "t-tag", "start"))
    b.append(f'<g data-step="1">{poly(A, B, C, D, cls="f-at")}'
             f'{poly(A, B, C, D, cls="s-ink")}</g>')
    b.append(f'<g data-step="2">{line(D, Hh, "s-teal dash")}'
             f'{right_mark(Hh, B, D, 11, "s-teal")}'
             f'{txt(P(Hh.x + 12, (y0 + y1) / 2), "h", "t-mono t-teal", "start")}</g>')
    # the triangle that gets cut and moved
    b.append(f'<g data-step="3">{poly(A, Hh, D, cls="f-vt")}'
             f'{poly(A, Hh, D, cls="s-violet")}</g>')
    Hh2 = P(B.x + sh, y0)
    b.append(f'<g data-step="4">{poly(B, Hh2, C, cls="f-vt")}'
             f'{poly(B, Hh2, C, cls="s-violet dash")}</g>')
    b.append(f'<g data-step="5">'
             f'{poly(Hh, Hh2, C, D, cls="s-accent thick")}'
             f'{txt(P((Hh.x + Hh2.x) / 2, (y0 + y1) / 2), "สี่เหลี่ยมผืนผ้า b × h", "t-mono t-accent")}</g>')
    for nm, p, dx, dy in (("A", A, -16, 8), ("B", B, -4, 22), ("C", C, 16, 2),
                          ("D", D, -8, -12)):
        b.append(dot(p, 4.2))
        b.append(txt(P(p.x + dx, p.y + dy), nm, "t-name"))
    rows = [
        (r"สี่เหลี่ยมด้านขนาน \(ABCD\) ฐาน \(AB=b\)", "รูปที่กำหนด"),
        (r"ลากความสูง \(DH\perp AB\) ยาว \(h\)", "สร้างเส้นช่วย"),
        (r"ตัดสามเหลี่ยม \(AHD\) ออก", r"สามเหลี่ยมมุมฉากที่มีด้านประกอบ \(h\)"),
        (r"สามเหลี่ยม \(AHD\equiv\) สามเหลี่ยมที่เลื่อนไปทางขวา",
         "เลื่อนขนานด้วยเวกเตอร์ \\(\\overrightarrow{AB}\\) → เท่ากันทุกประการ"),
        (r"รูปที่ได้เป็นสี่เหลี่ยมผืนผ้า \(b\times h\) ⇒ พื้นที่ \(=bh\)",
         "การตัดและเลื่อนไม่เปลี่ยนพื้นที่"),
    ]
    return fig_proof(
        "proof-shear", "การพิสูจน์สูตรพื้นที่สี่เหลี่ยมด้านขนาน",
        "สี่เหลี่ยมด้านขนานถูกตัดสามเหลี่ยมมุมฉากด้านซ้ายออก แล้วเลื่อนไปต่อด้านขวา "
        "กลายเป็นสี่เหลี่ยมผืนผ้าที่มีฐานและความสูงเท่าเดิม "
        "แสดงว่าพื้นที่เท่ากับฐานคูณความสูง",
        460, 300, "".join(b), rows,
        "นี่คือสิ่งที่ GeoGebra ทำให้เห็นได้ง่ายที่สุด — ลองสร้างสี่เหลี่ยมด้านขนาน "
        "แล้ว <b>ลากจุดยอดบนไปตามเส้นขนาน</b> พื้นที่ที่โปรแกรมแสดงจะไม่เปลี่ยน "
        "เลยแม้รูปจะเอียงมากขึ้น เพราะฐานและความสูงยังเท่าเดิม "
        "(การแปลงแบบนี้เรียกว่า <i>shear</i>)",
    )


